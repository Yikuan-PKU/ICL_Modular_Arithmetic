#SBATCH -N 1
#SBATCH -o RHM_%j.out
#SBATCH -e RHM_%j.err
#SBATCH --no-requeue
#SBATCH -A qi_g1
#SBATCH --qos=qig4c
#SBATCH --gres=gpu:1
#SBATCH --overcommit
#SBATCH --mincpus=9

source ~/lustre1/ykzhang/apps/python-3.11.11/venvICL/bin/activate


SCRIPT_ROOT="$HOME/lustre1/ykzhang/ICL_RHM/ICL_Modular_Arithmetic/src/scripts/eval"

# Define experiment parameters (same as collection phase)
DATASET_TYPE="uniform"     # or "zipf"
MIXTURE_TYPE="allmix"      # mixture configuration
TOTAL_RULES=576           # total number of rules
SEED=42                   # random seed

# Construct shared arguments (same pattern as collection)
SHARED_ARGS="--dataset-type $DATASET_TYPE --mixture-type $MIXTURE_TYPE --total-rules $TOTAL_RULES --seed $SEED"

# Experiment-specific arguments
EXP4_ARGS="--induction-threshold 0.3 --copying-threshold 0.3 --previous-token-threshold 0.3"

# Pipeline control arguments
PIPELINE_ARGS="--verbose"

# Experiment name for reference (auto-generated by scripts)
EXP_NAME="${DATASET_TYPE}_${MIXTURE_TYPE}_${TOTAL_RULES}_${SEED}"

# Create log directory if it doesn't exist
mkdir -p /scratch2/jliu/ICL/logs/exp

# Step 1: Check attention data availability
echo "Step 1: Checking attention data availability..."
python $SCRIPT_ROOT/attention.py $SHARED_ARGS --check-attention-data

if [ $? -ne 0 ]; then
    echo "ERROR: Attention data not available"
    echo "Please run the collection phase with attention capture enabled:"
    echo "  python collection.py $SHARED_ARGS --capture-attention"
    echo ""
    echo "Or check if collection was run with --no-attention flag"
    exit 1
fi

echo "✓ Attention data available"

# Step 2: Validate experiment setup
echo ""
echo "Step 2: Validating experiment setup..."
python $SCRIPT_ROOT/attention.py $SHARED_ARGS --validate-only

# Step 3: Run Experiment 4 - Attention Pattern Analysis
echo ""
echo "Step 3: Running Attention Pattern Analysis..."
echo "Command: python $SCRIPT_ROOT/attention.py $SHARED_ARGS $EXP4_ARGS $PIPELINE_ARGS"
echo ""

python $SCRIPT_ROOT/attention.py $SHARED_ARGS $EXP4_ARGS $PIPELINE_ARGS
