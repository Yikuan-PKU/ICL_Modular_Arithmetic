SCRIPT_ROOT="/scratch2/jliu/ICL/ICL_Modular_Arithmetic/src/scripts/eval"

# Define experiment parameters (only need to set once)
DATASET_TYPE="uniform"    # or zipf
MIXTURE_TYPE="allmix"
TOTAL_RULES=576
SEED=42

# Construct shared arguments
SHARED_ARGS="--dataset-type $DATASET_TYPE --mixture-type $MIXTURE_TYPE --total-rules $TOTAL_RULES --seed $SEED"

# Optional pipeline controls
PIPELINE_ARGS="--verbose"

# Experiment name for reference (auto-generated by scripts)
EXP_NAME="${DATASET_TYPE}_${MIXTURE_TYPE}_${TOTAL_RULES}_${SEED}"

echo "=========================================="
echo "ICL EVALUATION COLLECTION"
echo "=========================================="
echo "Experiment: $EXP_NAME"
echo "GPU allocation: $SLURM_GPUS_ON_NODE"
echo "Memory: $SLURM_MEM_PER_NODE MB"
echo "=========================================="

# Step 1: Validate configuration (optional)
echo "Step 1: Validating collection configuration..."
python $SCRIPT_ROOT/collection.py $SHARED_ARGS --validate-only

# Step 2: Run collection
echo "Step 2: Running collection..."
python $SCRIPT_ROOT/collection.py $SHARED_ARGS $PIPELINE_ARGS --overwrite