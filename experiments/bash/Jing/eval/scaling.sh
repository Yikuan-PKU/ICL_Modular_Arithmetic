# Construct shared arguments (same pattern as collection)
SHARED_ARGS="--dataset-type $DATASET_TYPE --mixture-type $MIXTURE_TYPE --total-rules $TOTAL_RULES --seed $SEED"

# Experiment-specific arguments
EXP3_ARGS="--performance-thresholds 0.5 0.7 0.9 --scaling-laws exponential power logarithmic --min-models 5"

# Pipeline control arguments
PIPELINE_ARGS="--verbose"

# Experiment name for reference (auto-generated by scripts)
EXP_NAME="${DATASET_TYPE}_${MIXTURE_TYPE}_${TOTAL_RULES}_${SEED}"

echo "=========================================="
echo "EXPERIMENT 3: CONTEXT SCALING ANALYSIS"
echo "=========================================="
echo "Experiment: $EXP_NAME"
echo "Expected collection results: $EXP_NAME/collection/"
echo "Output directory: $EXP_NAME/exp/exp3/"
echo "Memory allocation: $SLURM_MEM_PER_NODE MB"
echo "CPUs: $SLURM_CPUS_PER_TASK"
echo "=========================================="

# Create log directory if it doesn't exist
mkdir -p /scratch2/jliu/ICL/logs/exp

# Step 1: Validate experiment setup (optional)
echo "Step 1: Validating experiment setup..."
python $SCRIPT_ROOT/scaling.py $SHARED_ARGS --validate-only

# Step 2: Run Experiment 3 - Context Scaling Analysis
echo ""
echo "Step 2: Running Context Scaling Analysis..."
echo "Command: python $SCRIPT_ROOT/scaling.py $SHARED_ARGS $EXP3_ARGS $PIPELINE_ARGS"
echo ""

python $SCRIPT_ROOT/scaling.py $SHARED_ARGS $EXP3_ARGS $PIPELINE_ARGS
